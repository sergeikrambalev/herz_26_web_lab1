function add(a, b) {
  return a + b;
}

// eslint-disable-next-line no-unused-vars
function sub(a, b) {
  return a - b;
}

// eslint-disable-next-line no-unused-vars
function mul(a, b) {
  return a * b;
}

// eslint-disable-next-line no-unused-vars
function div(a, b) {
  if (b === 0) {
    return null;
  }
  return a / b;
}

